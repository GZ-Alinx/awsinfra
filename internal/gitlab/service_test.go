func assertYAMLDocuments(t *testing.T, content string, expected int) {
	t.Helper()
	content = strings.ReplaceAll(content, "{{IMAGE}}", "registry.example/app:v1")
	content = strings.ReplaceAll(content, "{{ETCD_PASSWORD}}", `"redacted"`)
	decoder := yaml.NewDecoder(strings.NewReader(content))
	count := 0
	for {
		var document map[string]any
		err := decoder.Decode(&document)
		if err == io.EOF {
			break
		}
		if err != nil {
			t.Fatalf("generated manifest is invalid YAML: %v\n%s", err, content)
		}
		if len(document) > 0 {
			count++
		}
	}
	if count != expected {
		t.Fatalf("generated manifest contains %d YAML documents, want %d\n%s", count, expected, content)
	}
}

