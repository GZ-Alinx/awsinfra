func TestProjectDeliveryUsesOneEnvironmentScopedRepository(t *testing.T) {
	store := newMemoryStore()
	service := newTestService(t, store)
	server, err := service.SaveServer(context.Background(), "", ServerInput{
		Key: "main", DisplayName: "Main GitLab", BaseURL: "https://gitlab.example.com", AccessToken: "secret-token",
		RootGroup: "ops/delivery", DefaultBranch: "main", Visibility: "private",
	})
	if err != nil || !server.Configured {
		t.Fatalf("SaveServer() = %#v, %v", server, err)
	}
	stored := store.servers["main"]
	if stored.TokenCipher == "" || strings.Contains(stored.TokenCipher, "secret-token") {
		t.Fatal("GitLab token was not encrypted")
	}
	delivery, err := service.SaveDelivery(context.Background(), "game-api", ProjectDelivery{ServerKey: "main", Services: []ServiceSpec{{
		Key: "gateway", DisplayName: "Gateway", Language: "go", SourceRepository: "https://gitlab.example.com/game/gateway.git",
		ImageRepository: "123456789012.dkr.ecr.ap-south-1.amazonaws.com/game-api/gateway",
	}}})
	if err != nil {
		t.Fatal(err)
	}
	if delivery.JenkinsfilesProjectPath != "ops/delivery/game-api-ops-delivery" || delivery.ManifestsProjectPath != delivery.JenkinsfilesProjectPath {
		t.Fatalf("unexpected repository paths: %#v", delivery)
	}
	if len(delivery.Services) != 1 || delivery.Services[0].Namespace != "game-api" || delivery.Services[0].SourceBranch != "main" {
		t.Fatalf("service defaults were not applied: %#v", delivery.Services)
	}
	files := generateDeliveryFiles("game-api", delivery, server)
	assertGeneratedPath(t, files, "delivery", "environments/dev/gateway/manifest.yaml")
	assertGeneratedPath(t, files, "delivery", "environments/dev/dockerfiles/gateway/Dockerfile")
	assertGeneratedPath(t, files, "delivery", "environments/prod/dockerfiles/gateway/Dockerfile")
	if delivery.Services[0].DockerfileSource != "platform" || delivery.Services[0].Dockerfile != "dockerfiles/gateway/Dockerfile" || !strings.Contains(delivery.Services[0].DockerfileContent, "FROM golang:1.24-bookworm") {
		t.Fatalf("managed Dockerfile defaults were not applied: %#v", delivery.Services[0])
	}
	for _, file := range files {
		if strings.HasSuffix(file.Path, "kustomization.yaml") {
			t.Fatalf("obsolete kustomization file was generated: %s", file.Path)
		}
	}
	for _, file := range files {
		if file.Repository == "delivery" && strings.Contains(file.Path, "services/gateway") {
			t.Fatalf("service Jenkinsfile must be generated by a CI/CD job, got %s", file.Path)
		}
	}
	for _, file := range files {
		if strings.Contains(file.Content, "secret-token") {
			t.Fatalf("secret leaked into generated file %s", file.Path)
		}
		if strings.Contains(file.Content, "%!") {
			t.Fatalf("formatting error in generated file %s: %s", file.Path, file.Content)
		}
	}
}

