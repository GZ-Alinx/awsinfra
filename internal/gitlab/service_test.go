type fakeGitLab struct {
	t        *testing.T
	server   *httptest.Server
	nextID   int64
	projects map[string]gitLabProject
	files    map[int64]map[string]string
}

func newFakeGitLab(t *testing.T) *fakeGitLab {
	fake := &fakeGitLab{t: t, nextID: 100, projects: map[string]gitLabProject{}, files: map[int64]map[string]string{}}
	fake.server = httptest.NewServer(http.HandlerFunc(fake.handle))
	return fake
}

func (f *fakeGitLab) handle(w http.ResponseWriter, r *http.Request) {
	w.Header().Set("Content-Type", "application/json")
	if r.Header.Get("PRIVATE-TOKEN") != "token" {
		http.Error(w, `{"message":"unauthorized"}`, http.StatusUnauthorized)
		return
	}
	path := strings.TrimPrefix(r.URL.Path, "/api/v4/")
	switch {
	case r.Method == http.MethodGet && path == "groups/ops/delivery":
		_ = json.NewEncoder(w).Encode(gitLabGroup{ID: 7, FullPath: "ops/delivery"})
	case r.Method == http.MethodPost && path == "projects":
		var input struct {
			Path string `json:"path"`
		}
		if err := json.NewDecoder(r.Body).Decode(&input); err != nil {
			f.t.Error(err)
			http.Error(w, `{}`, 400)
			return
		}
		fullPath := "ops/delivery/" + input.Path
		if _, exists := f.projects[fullPath]; exists {
			http.Error(w, `{"message":"taken"}`, http.StatusBadRequest)
			return
		}
		f.nextID++
		item := gitLabProject{ID: f.nextID, Path: input.Path, PathWithNamespace: fullPath, HTTPURLToRepo: f.server.URL + "/" + fullPath + ".git", DefaultBranch: "main"}
		f.projects[fullPath], f.files[item.ID] = item, map[string]string{}
		w.WriteHeader(http.StatusCreated)
		_ = json.NewEncoder(w).Encode(item)
	case r.Method == http.MethodGet && strings.HasPrefix(path, "projects/") && !strings.Contains(path, "/repository/"):
		fullPath := strings.TrimPrefix(path, "projects/")
		item, exists := f.projects[fullPath]
		if !exists {
			http.Error(w, `{"message":"404 Project Not Found"}`, http.StatusNotFound)
			return
		}
		_ = json.NewEncoder(w).Encode(item)
	case r.Method == http.MethodGet && strings.Contains(path, "/repository/tree"):
		id := fakeProjectID(path)
		if len(f.files[id]) == 0 {
			http.Error(w, `{"message":"404 Tree Not Found"}`, http.StatusNotFound)
			return
		}
		_ = json.NewEncoder(w).Encode([]map[string]any{{"id": "file"}})
	case r.Method == http.MethodGet && strings.Contains(path, "/repository/files/"):
		id := fakeProjectID(path)
		filePath := strings.SplitN(path, "/repository/files/", 2)[1]
		content, exists := f.files[id][filePath]
		if !exists {
			http.Error(w, `{"message":"404 File Not Found"}`, http.StatusNotFound)
			return
		}
		_ = json.NewEncoder(w).Encode(map[string]string{"encoding": "base64", "content": base64.StdEncoding.EncodeToString([]byte(content))})
	case r.Method == http.MethodPost && strings.HasSuffix(path, "/repository/commits"):
		id := fakeProjectID(path)
		var input struct {
			Actions []struct {
				Action   string `json:"action"`
				FilePath string `json:"file_path"`
				Content  string `json:"content"`
			} `json:"actions"`
		}
		if err := json.NewDecoder(r.Body).Decode(&input); err != nil {
			f.t.Error(err)
			http.Error(w, `{}`, 400)
			return
		}
		for _, action := range input.Actions {
			if action.Action == "delete" {
				delete(f.files[id], action.FilePath)
			} else {
				f.files[id][action.FilePath] = action.Content
			}
		}
		w.WriteHeader(http.StatusCreated)
		_, _ = w.Write([]byte(`{}`))
	default:
		f.t.Errorf("unexpected GitLab request: %s %s", r.Method, r.RequestURI)
		http.Error(w, fmt.Sprintf(`{"message":"unexpected %s"}`, r.RequestURI), http.StatusNotFound)
	}
}

func fakeProjectID(path string) int64 {
	value := strings.TrimPrefix(path, "projects/")
	value = strings.SplitN(value, "/", 2)[0]
	id, _ := strconv.ParseInt(value, 10, 64)
	return id
}

type memoryStore struct {
	servers    map[string]StoredServer
	deliveries map[string]ProjectDelivery
	repos      map[string]cicd.Repository
}

func newMemoryStore() *memoryStore {
	return &memoryStore{servers: map[string]StoredServer{}, deliveries: map[string]ProjectDelivery{}, repos: map[string]cicd.Repository{}}
}

func (m *memoryStore) ListGitLabServers(context.Context) ([]StoredServer, error) {
	items := []StoredServer{}
	for _, item := range m.servers {
		items = append(items, item)
	}
	return items, nil
}
func (m *memoryStore) GetGitLabServer(_ context.Context, key string) (StoredServer, error) {
	item, ok := m.servers[key]
	if !ok {
		return item, os.ErrNotExist
	}
	return item, nil
}
func (m *memoryStore) SaveGitLabServer(_ context.Context, item StoredServer) error {
	now := time.Now().UTC()
	if item.CreatedAt.IsZero() {
		item.CreatedAt = now
	}
	item.UpdatedAt = now
	m.servers[item.Key] = item
	return nil
}
func (m *memoryStore) DeleteGitLabServer(_ context.Context, key string) error {
	delete(m.servers, key)
	return nil
}
func (m *memoryStore) GitLabServerBindingCount(_ context.Context, key string) (int, error) {
	count := 0
	for _, item := range m.deliveries {
		if item.ServerKey == key || item.SourceServerKey == key {
			count++
		}
	}
	return count, nil
}
func (m *memoryStore) GitLabServerBindingRootGroups(_ context.Context, key string) ([]string, error) {
	groups := []string{}
	seen := map[string]bool{}
	for _, item := range m.deliveries {
		for _, binding := range []struct{ server, group string }{{item.ServerKey, item.RootGroup}, {item.SourceServerKey, item.SourceRootGroup}} {
			if binding.server == key && binding.group != "" && !seen[strings.ToLower(binding.group)] {
				seen[strings.ToLower(binding.group)] = true
				groups = append(groups, binding.group)
			}
		}
	}
	return groups, nil
}
func (m *memoryStore) GitLabServerSourceRepositories(_ context.Context, key string) ([]string, error) {
	result := []string{}
	for _, item := range m.deliveries {
		if item.SourceServerKey != key {
			continue
		}
		for _, service := range item.Services {
			if service.SourceRepository != "" {
				result = append(result, service.SourceRepository)
			}
		}
	}
	return result, nil
}
func (m *memoryStore) GetProjectGitLabDelivery(_ context.Context, project string) (ProjectDelivery, error) {
	item, ok := m.deliveries[project]
	if !ok {
		return item, os.ErrNotExist
	}
	return item, nil
}
func (m *memoryStore) SaveProjectGitLabDelivery(_ context.Context, item ProjectDelivery) error {
	now := time.Now().UTC()
	if item.CreatedAt.IsZero() {
		item.CreatedAt = now
	}
	item.UpdatedAt = now
	m.deliveries[item.ProjectKey] = item
	return nil
}
func (m *memoryStore) DetachProjectGitLabDelivery(_ context.Context, project string) error {
	item, ok := m.deliveries[project]
	if !ok {
		return os.ErrNotExist
	}
	item.ServerKey = ""
	item.RootGroup = ""
	item.SourceServerKey = ""
	item.SourceRootGroup = ""
	item.JenkinsfilesProjectID = 0
	item.JenkinsfilesProjectPath = ""
	item.JenkinsfilesCloneURL = ""
	item.ManifestsProjectID = 0
	item.ManifestsProjectPath = ""
	item.ManifestsCloneURL = ""
	item.ProvisionStatus = ""
	item.ProvisionError = ""
	item.LastProvisionedAt = time.Time{}
	m.deliveries[project] = item
	return nil
}
func (m *memoryStore) GetCICDRepository(_ context.Context, project, key string) (cicd.Repository, error) {
	item, ok := m.repos[project+"/"+key]
	if !ok {
		return item, os.ErrNotExist
	}
	return item, nil
}
func (m *memoryStore) SaveCICDRepository(_ context.Context, item cicd.Repository) error {
	m.repos[item.ProjectKey+"/"+item.Key] = item
	return nil
}
